// TestServerReloadPicksUpCA verifies the server can start with no cached CA
// (first boot) and, after Reload, trusts the CA that lands on disk.
func TestServerReloadPicksUpCA(t *testing.T) {
	is := assert.New(t)
	must := require.New(t)
	ca := newTestCA(t)
	configDir := t.TempDir()
	t.Setenv("NOKKUD_DATA_DIR", configDir)

	// No CA file yet: New must not fail and generates a host key into the
	// state directory.
	srv, err := New(Options{
		Principals: func(username string) []string {
			if username == currentUser(t) {
				return []string{testPrincipal}
			}
			return nil
		},
		TrustedCAs: []ssh.PublicKey{ca.pub},
	})
	must.NoError(err, "new server without CA")
	defer srv.hostKeyDev.Close()

	// Now the CA file appears (as the cert sync would write it) and Reload
	// must pick it up.
	must.NoError(os.WriteFile(
		filepath.Join(configDir, "nokku_ca.pub"),
		ssh.MarshalAuthorizedKey(ca.pub),
		0o644,
	))
	srv.Reload()
	is.True(srv.trustedCA(ca.pub), "reloaded server does not trust the CA that landed on disk")
}

// TestLoadTrustedCAsRetiredGrace verifies the retired CA stays trusted for
// the rollover grace window and drops off afterwards, while the active CA
// always remains trusted. With drop_retired_ca the retired CA is dropped at
// once and its file removed.
func TestLoadTrustedCAsRetiredGrace(t *testing.T) {
	is := assert.New(t)
	must := require.New(t)
	active := newTestCA(t)
	retired := newTestCA(t)
	configDir := t.TempDir()
	t.Setenv("NOKKUD_DATA_DIR", configDir)

	writeCAFile := func(name string, ca testCA) {
		t.Helper()
		must.NoError(os.WriteFile(
			filepath.Join(configDir, name),
			ssh.MarshalAuthorizedKey(ca.pub),
			0o644,
		))
	}
	trusts := func(keys []ssh.PublicKey, ca testCA) bool {
		t.Helper()
		for _, k := range keys {
			if bytes.Equal(k.Marshal(), ca.pub.Marshal()) {
				return true
			}
		}
		return false
	}

	writeCAFile("nokku_ca.pub", active)
	keys, err := loadTrustedCAs(false)
	must.NoError(err)
	is.True(trusts(keys, active), "active CA must be trusted")
	is.False(trusts(keys, retired), "no retired CA present")

	// A fresh retired CA (recent mtime) is trusted alongside the active one.
	writeCAFile("nokku_ca.previous.pub", retired)
	keys, err = loadTrustedCAs(false)
	must.NoError(err)
	is.True(trusts(keys, active), "active CA must stay trusted during the grace window")
	is.True(trusts(keys, retired), "retired CA must stay trusted during the grace window")

	// After the grace window the retired CA is no longer trusted.
	old := time.Now().Add(-retiredCAGrace - time.Hour)
	must.NoError(os.Chtimes(filepath.Join(configDir, "nokku_ca.previous.pub"), old, old))
	keys, err = loadTrustedCAs(false)
	must.NoError(err)
	is.False(trusts(keys, retired), "retired CA must stop being trusted after the grace window")
	is.True(trusts(keys, active), "active CA must remain trusted")

	// A corrupt retired CA must not break authentication.
	must.NoError(os.WriteFile(
		filepath.Join(configDir, "nokku_ca.previous.pub"),
		[]byte("garbage"),
		0o644,
	))
	keys, err = loadTrustedCAs(false)
	must.NoError(err, "corrupt retired CA must not fail the load")
	is.True(trusts(keys, active), "active CA must remain trusted with a corrupt retired CA")

	// With drop_retired_ca a fresh retired CA is not trusted, and its file is
	// removed so trust cannot come back on a later load.
	writeCAFile("nokku_ca.previous.pub", retired)
	keys, err = loadTrustedCAs(true)
	must.NoError(err)
	is.True(trusts(keys, active), "active CA must stay trusted when dropping the retired CA")
	is.False(trusts(keys, retired), "retired CA must not be trusted inside the grace window")

	_, statErr := os.Stat(filepath.Join(configDir, "nokku_ca.previous.pub"))
	is.True(os.IsNotExist(statErr), "retired CA file must be removed")

	keys, err = loadTrustedCAs(false)
	must.NoError(err)
	is.False(trusts(keys, retired), "a removed retired CA must not come back")

	// Removing an already absent file is not a failure.
	_, err = loadTrustedCAs(true)
	must.NoError(err)
}

// TestServerReloadRefreshesHostCerts verifies Reload adopts a newly written
// host certificate for the host key.
func TestServerReloadRefreshesHostCerts(t *testing.T) {
	is := assert.New(t)
	must := require.New(t)
	ca := newTestCA(t)
	configDir := t.TempDir()
	t.Setenv("NOKKUD_DATA_DIR", configDir)

	srv, err := New(Options{
		Principals: func(username string) []string {
			if username == currentUser(t) {
				return []string{testPrincipal}
			}
			return nil
		},
		TrustedCAs: []ssh.PublicKey{ca.pub},
	})
	must.NoError(err, "new server")
	defer srv.hostKeyDev.Close()

	// Read the host key generated by New, sign it as a host cert, and write
	// the cert next to it, as RenewHostCerts would.
	pubData, err := os.ReadFile(paths.HostKeyPub())
	must.NoError(err)
	hostPub, _, _, _, err := ssh.ParseAuthorizedKey(pubData)
	must.NoError(err)
	cert := &ssh.Certificate{
		Key:         hostPub,
		CertType:    ssh.HostCert,
		KeyId:       "host-test",
		ValidAfter:  0,
		ValidBefore: ssh.CertTimeInfinity,
	}
	must.NoError(cert.SignCert(rand.Reader, ca.signer))
	certPath := paths.HostKeyCert()
	must.NoError(os.WriteFile(certPath, ssh.MarshalAuthorizedKey(cert), 0o644))

	srv.Reload()

	// A host cert signer's PublicKey() returns the certificate itself.
	srv.mu.RLock()
	cfg := srv.cfg
	srv.mu.RUnlock()
	_, hasCert := hostPublicKey(t, cfg).(*ssh.Certificate)
	is.True(hasCert, "reload did not adopt the host certificate")
}

// TestParseCAFileSkipsComments verifies blank lines and comments in the CA
// file are tolerated, matching the authorized_keys format it mirrors.
func TestParseCAFileSkipsComments(t *testing.T) {
	is := assert.New(t)
	must := require.New(t)
	ca := newTestCA(t)
	path := filepath.Join(t.TempDir(), "ca.pub")

	content := "# trusted CAs\n\n" + string(ssh.MarshalAuthorizedKey(ca.pub)) + "\n# trailing comment\n"
	must.NoError(os.WriteFile(path, []byte(content), 0o644))

	keys, err := parseCAFile(path)
	must.NoError(err, "comments must not fail the parse")
	is.Len(keys, 1, "expected exactly one CA key")
	is.True(bytes.Equal(keys[0].Marshal(), ca.pub.Marshal()))
}

// TestServerReloadKeepsPreviousCAOnError verifies a CA file that becomes
// unreadable between reloads does not blank the trust set: logins keep
// working with the last known good CAs until the next successful sync.
func TestServerReloadKeepsPreviousCAOnError(t *testing.T) {
	is := assert.New(t)
	must := require.New(t)
	ca := newTestCA(t)
	configDir := t.TempDir()
	t.Setenv("NOKKUD_DATA_DIR", configDir)

	srv, err := New(Options{
		Principals: func(username string) []string {
			if username == currentUser(t) {
				return []string{testPrincipal}
			}
			return nil
		},
		TrustedCAs: []ssh.PublicKey{ca.pub},
	})
	must.NoError(err, "new server")
	defer srv.hostKeyDev.Close()

	must.NoError(os.WriteFile(
		filepath.Join(configDir, "nokku_ca.pub"),
		ssh.MarshalAuthorizedKey(ca.pub),
		0o644,
	))
	srv.Reload()

	// A corrupt CA file (sync raced by an editor, disk glitch, ...) must
	// leave the previous trust set in place so logins keep working.
	must.NoError(os.WriteFile(filepath.Join(configDir, "nokku_ca.pub"), []byte("garbage"), 0o644))
	srv.Reload()
	is.True(srv.trustedCA(ca.pub), "previous trust set was dropped on reload error")
}

// hostPublicKey handshakes against cfg and returns the host key it presents.
func hostPublicKey(t *testing.T, cfg *ssh.ServerConfig) ssh.PublicKey {
	t.Helper()
	l, err := net.Listen("tcp", "127.0.0.1:0")
	require.NoError(t, err)
	defer l.Close()
	go func() {
		nc, acceptErr := l.Accept()
		if acceptErr != nil {
			return
		}
		defer nc.Close()
		_, _, _, _ = ssh.NewServerConn(nc, cfg)
	}()
	c1, err := net.Dial("tcp", l.Addr().String())
	require.NoError(t, err)
	defer c1.Close()
	var got ssh.PublicKey
	_, _, _, _ = ssh.NewClientConn(c1, "pipe", &ssh.ClientConfig{
		HostKeyCallback: func(_ string, _ net.Addr, key ssh.PublicKey) error {
			got = key
			return errors.New("done")
		},
		HostKeyAlgorithms: []string{ssh.CertAlgoECDSA256v01},
	})
	require.NotNil(t, got, "no host key presented")
	return got
}

// closingSigner cannot sign once closed, like a key held in a TPM.
type closingSigner struct {
	tpm.Signer

	closed atomic.Bool
}

func (c *closingSigner) Close() error {
	c.closed.Store(true)
	return c.Signer.Close()
}

func (c *closingSigner) Sign(rand io.Reader, digest []byte, opts crypto.SignerOpts) ([]byte, error) {
	if c.closed.Load() {
		return nil, errors.New("host key is closed")
	}
	return c.Signer.Sign(rand, digest, opts)
}

// TestReloadKeepsHostKeyOpen verifies a connection made before a reload can
// still rekey after it. Every key exchange signs with the host key again.
func TestReloadKeepsHostKeyOpen(t *testing.T) {
	must := require.New(t)
	open := newHostSigner
	newHostSigner = func(opts tpm.SignerOptions) (tpm.Signer, error) {
		signer, err := open(opts)
		if err != nil {
			return nil, err
		}
		return &closingSigner{Signer: signer}, nil
	}
	t.Cleanup(func() { newHostSigner = open })

	ca := newTestCA(t)
	var srv *Server
	addr, closeFn := startTestServerOpts(t, ca, Options{}, func(s *Server) { srv = s })
	defer closeFn()

	client, err := ssh.Dial("tcp", addr, &ssh.ClientConfig{
		RekeyThreshold:  1024,
		User:            currentUser(t),
		Auth:            []ssh.AuthMethod{userCert(t, ca, testPrincipal)},
		HostKeyCallback: ssh.InsecureIgnoreHostKey(), // #nosec G106 - test server
		Timeout:         10 * time.Second,
	})
	must.NoError(err, "dial")
	defer client.Close()

	srv.Reload()

	sess, err := client.NewSession()
	must.NoError(err, "session after reload")
	defer sess.Close()
	out, err := sess.Output("head -c 200000 /dev/zero")
	must.NoError(err, "the connection broke when it rekeyed after a reload")
	must.Len(out, 200000)
}
